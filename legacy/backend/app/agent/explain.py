"""Explanation node.

The narrative is generated by an LLM only when an API key is configured.
Otherwise a deterministic, template-based analyst note is produced from the
same evidence, so the product is fully usable and testable offline.

Guardrails baked into both paths:
* never recommend a specific trade, size or limit change;
* state that a human owns the decision;
* quote only numbers that are present in the snapshot.
"""

from __future__ import annotations

import json
import re
from typing import Any

import httpx

from ..config import Settings

ACTIONS_BY_CODE: dict[str, list[str]] = {
    "VAR_LIMIT": [
        "Review the largest risk contributors and decide whether the exposure still matches the mandate.",
        "Re-run the check after any rebalance so the audit trail shows the effect.",
    ],
    "VOL_LIMIT": [
        "Check whether the volatility rise is broad or driven by one or two names.",
        "Confirm the risk budget with the desk before changing anything.",
    ],
    "DRAWDOWN_LIMIT": [
        "Escalate to the risk committee and confirm the drawdown limit still fits the mandate.",
        "Document the decision in the audit log, including who reviewed it.",
    ],
    "DAILY_MOVE": [
        "Verify the move against news or earnings before reacting to a single session.",
        "Compare the move with the model's expected 1-day loss range.",
    ],
    "CONCENTRATION": [
        "Agree a plan to bring the largest position back toward the concentration guideline.",
        "Check that the position is intentional rather than drift from price moves.",
    ],
    "UNUSUAL_ACTIVITY": [
        "Inspect the flagged names before changing weights; unusual moves can be data noise.",
        "Confirm the price feed is complete and correctly adjusted.",
    ],
}

ALWAYS_ACTIONS = [
    "A human reviewer must approve any trade, hedge or limit change.",
]


def _pct(value: float, digits: int = 2) -> str:
    return f"{value * 100:.{digits}f}%"


def _money(value: float) -> str:
    return f"${value:,.0f}"


def rule_based_explanation(
    snapshot: dict[str, Any],
    findings: dict[str, Any],
    limits: dict[str, float],
    note: str | None = None,
) -> dict[str, Any]:
    metrics = snapshot["metrics"]
    breaches = snapshot["breaches"]
    assets = snapshot["assets"]
    top = assets[0] if assets else None
    flagged = snapshot["anomalies"]["symbols"]
    count = len(breaches)
    positions = f"{len(flagged)} position{'s' if len(flagged) != 1 else ''}"

    if breaches:
        primary = next((item for item in breaches if item.get("unit") == "%"), None)
        if primary:
            headline = (
                f"{count} risk limit{'s' if count != 1 else ''} "
                f"{'need' if count != 1 else 'needs'} a human decision"
            )
        else:
            headline = f"{positions} {'need' if len(flagged) != 1 else 'needs'} a closer look"
        if primary:
            narrative = (
                f"As of {snapshot['as_of']}, {primary['metric'].lower()} is {primary['observed']}% against a "
                f"{primary['limit']}% limit. The portfolio's 1-day 95% VaR is {_pct(metrics['var_95_1d'])} of NAV "
                f"({_money(metrics['var_95_usd'])}), and expected shortfall — the average loss when that tail "
                f"is breached — is {_pct(metrics['es_95_1d'])} ({_money(metrics['es_95_usd'])}). "
            )
        else:
            narrative = (
                f"As of {snapshot['as_of']}, every market-risk limit is intact, but {positions} "
                f"{'show' if len(flagged) != 1 else 'shows'} unusual price behaviour. The portfolio's 1-day 95% "
                f"VaR is {_pct(metrics['var_95_1d'])} of NAV ({_money(metrics['var_95_usd'])}), and expected "
                f"shortfall is {_pct(metrics['es_95_1d'])} ({_money(metrics['es_95_usd'])}). "
            )
        if top:
            narrative += (
                f"{top['symbol']} is the largest risk contributor at {top['risk_share'] * 100:.0f}% of total risk. "
            )
            if primary and flagged:
                narrative += f"{positions} also {'show' if len(flagged) != 1 else 'shows'} unusual price behaviour. "
        narrative += (
            "These are measured risks, not forecasts, and nothing here authorises a trade. "
            "A human reviewer owns the decision."
        )
    else:
        headline = "Inside the agreed risk appetite"
        narrative = (
            f"Across the last {metrics['observations']} sessions to {snapshot['as_of']}, the portfolio's 1-day "
            f"95% VaR is {_pct(metrics['var_95_1d'])} of NAV ({_money(metrics['var_95_usd'])}) and expected "
            f"shortfall is {_pct(metrics['es_95_1d'])}. Annualised volatility of {_pct(metrics['ann_vol'])} "
            f"and a drawdown of {abs(metrics['current_drawdown']) * 100:.1f}% from the peak are within the "
            f"limits set for this portfolio."
        )
        if top:
            narrative += (
                f" {top['symbol']} carries the most risk at {top['risk_share'] * 100:.0f}% of the total."
            )

    actions: list[str] = []
    for breach in breaches:
        for action in ACTIONS_BY_CODE.get(breach["code"], []):
            if action not in actions:
                actions.append(action)
    if not actions:
        actions = [
            "No action required; keep the scheduled monitoring cycle running.",
            "Revisit the limits if the portfolio or mandate changes.",
        ]
    actions.append(ALWAYS_ACTIONS[0])

    return {
        "headline": headline,
        "narrative": narrative,
        "actions": actions[:5],
        "mode": "rule-based",
        "model": None,
        "note": note,
        "generated_at": snapshot["as_of"],
    }


def _extract_json(text: str) -> dict[str, Any] | None:
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", cleaned)
    match = re.search(r"\{.*\}", cleaned, re.DOTALL)
    if not match:
        return None
    try:
        payload = json.loads(match.group(0))
    except json.JSONDecodeError:
        return None
    if not isinstance(payload, dict):
        return None
    if not payload.get("headline") or not payload.get("narrative"):
        return None
    actions = payload.get("actions")
    if not isinstance(actions, list):
        actions = []
    payload["actions"] = [str(action) for action in actions][:4]
    return payload


def _evidence(snapshot: dict[str, Any], limits: dict[str, float]) -> dict[str, Any]:
    metrics = snapshot["metrics"]
    return {
        "as_of": snapshot["as_of"],
        "data_source": snapshot["data_source"],
        "portfolio_value": metrics["portfolio_value"],
        "risk_metrics_pct_of_nav": {
            "var_95_1d": round(metrics["var_95_1d"] * 100, 3),
            "var_99_1d": round(metrics["var_99_1d"] * 100, 3),
            "var_95_5d": round(metrics["var_95_5d"] * 100, 3),
            "expected_shortfall_95_1d": round(metrics["es_95_1d"] * 100, 3),
            "annualised_volatility": round(metrics["ann_vol"] * 100, 3),
            "current_drawdown": round(metrics["current_drawdown"] * 100, 3),
            "latest_session_return": round(metrics["latest_return"] * 100, 3),
        },
        "limits_pct": limits,
        "breaches": snapshot["breaches"],
        "top_risk_contributors": [
            {
                "symbol": asset["symbol"],
                "name": asset["name"],
                "risk_share_pct": round(asset["risk_share"] * 100, 1),
                "weight_pct": round(asset["weight"] * 100, 1),
            }
            for asset in snapshot["assets"][:4]
        ],
        "unusual_activity": snapshot["anomalies"]["details"],
        "health_score": snapshot["health"],
    }


SYSTEM_PROMPT = (
    "You are a market-risk analyst assistant inside a portfolio monitoring tool. "
    "Explain the supplied risk snapshot in plain business English for a portfolio manager. "
    "Use only the numbers provided. Do not recommend specific trades, position sizes or limit changes. "
    "Do not claim certainty or predict prices. Keep the narrative to 3-4 sentences and give 2-4 "
    "short next steps for a human reviewer. Return ONLY JSON with the keys "
    '"headline" (max 8 words), "narrative" (string), "actions" (array of short strings).'
)


async def explain(
    snapshot: dict[str, Any],
    findings: dict[str, Any],
    limits: dict[str, float],
    settings: Settings,
) -> dict[str, Any]:
    """Try the LLM, fall back to the deterministic note on any problem."""
    fallback = rule_based_explanation(snapshot, findings, limits)
    if not settings.llm_enabled:
        return fallback

    payload = {
        "model": settings.llm_model,
        "temperature": 0.2,
        "max_tokens": 650,
        "response_format": {"type": "json_object"},
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": "Risk snapshot:\n"
                + json.dumps(_evidence(snapshot, limits), indent=2, default=str),
            },
        ],
    }

    try:
        async with httpx.AsyncClient(timeout=settings.llm_timeout_seconds) as client:
            response = await client.post(
                f"{settings.llm_base_url}/chat/completions",
                headers={
                    "Authorization": f"Bearer {settings.llm_api_key}",
                    "Content-Type": "application/json",
                },
                json=payload,
            )
            response.raise_for_status()
            body = response.json()
        content = body["choices"][0]["message"]["content"]
        parsed = _extract_json(content)
        if not parsed:
            return rule_based_explanation(
                snapshot, findings, limits, note="The model reply was not valid JSON; rule-based note used."
            )
        return {
            "headline": str(parsed["headline"])[:90],
            "narrative": str(parsed["narrative"]),
            "actions": (parsed["actions"] + ALWAYS_ACTIONS)[:5],
            "mode": "llm",
            "model": settings.llm_model,
            "note": None,
            "generated_at": snapshot["as_of"],
        }
    except Exception as exc:  # timeouts, auth, quota, malformed responses
        return rule_based_explanation(
            snapshot,
            findings,
            limits,
            note=f"LLM call unavailable ({type(exc).__name__}); rule-based note used.",
        )
